/* ============================================================================
 * ai.h —— 五子棋 AI 对手（轨道 D）
 * ----------------------------------------------------------------------------
 * 和其它文件一样是**平台无关的纯逻辑**：只依赖 <stdint.h> + board.h，
 * 不用 libc / 不用动态内存 / 不用浮点 —— 可以在 x86 上跑单测（test_ai.c），
 * 也能原样编进 RV32 裸机固件。
 *
 * 架构（为什么这么分）：
 *   评分函数（heuristic）  快、粗 —— 只负责给候选走法【排序】和给叶子节点【估值】
 *   搜索（alpha-beta）     慢、细 —— 负责找战术：跳三/跳四/双三这类断点棋型
 * 所以评分函数不需要做到"棋型识别完美"，把断点交给搜索去发现就行。
 * 这是刻意取舍：单纯堆评分表会在 RV32 上越来越慢，而搜索宽度可以用 WIDTH 卡住。
 *
 * [!] 本文件的所有函数都**不修改**传入的棋盘 —— 搜索内部用 place/undo，
 *     返回时棋盘与传入时逐字节相同（test_ai.c 里有这条断言）。
 * ==========================================================================*/
#ifndef GOMOKU_AI_H
#define GOMOKU_AI_H

#include <stdint.h>
#include "board.h"

/* 难度档
 * [!] 别给 NORMAL 用 2 层 —— 实测那样会输给对手的活三（看得不够深，
 *     叶子估值把对手的威胁当成白送的）。4 层是"能看穿活三威胁"的最低档。 */
#define AI_EASY     0   /* 贪心：只按评分取最高分那一手（不搜索） */
#define AI_NORMAL   1   /* alpha-beta 搜 4 层 */
#define AI_HARD     2   /* alpha-beta 搜 6 层 */

/* 搜索统计 —— 工作清单要求"打印搜索节点数 / 深度 / 耗时"，这是数据源。
 * 给上层打印用；aborted 是内部字段，外面看个热闹就行。 */
typedef struct {
    uint32_t nodes;     /* 展开的节点数 */
    uint32_t leaves;    /* 其中叶子节点数 */
    uint8_t  depth;     /* **实际完成**的搜索深度（可能小于档位，见 aborted） */
    uint8_t  aborted;   /* 内部用：节点数超预算、提前收工（此时用的是上一轮结果） */
    int32_t  score;     /* 选中那一手的评分（越大越好） */
} ai_stats_t;

/* 为 `g->turn` 这一方选一手棋。
 *   成功    -> 返回 GOMOKU_OK，并写 *out_r / *out_c
 *   无子可下 -> 返回非 0（棋盘满了）
 * `stats` 可以为 NULL。
 * **只读 `g`** —— 内部搜索完会完整还原。 */
int ai_choose_move(const gomoku_t *g, int level, int *out_r, int *out_c,
                   ai_stats_t *stats);

/* 给定局面下，`who` 在 (r,c) 落子的"价值"（进攻 + 防守，越大越好）。
 * 越界或该点已有子返回一个很负的值。给单测和 HUD 提示用。 */
int32_t ai_move_score(const gomoku_t *g, int r, int c, int who);

#endif /* GOMOKU_AI_H */
