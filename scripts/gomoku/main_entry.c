/* ============================================================================
 * main_entry.c —— 裸机入口（只有这一个函数）
 * ----------------------------------------------------------------------------
 * 为什么把 main() 单独拆出来一个文件：
 *
 *   五子棋要同时跑在【裸机】和【RT-Thread】两种宿主上，而 RT-Thread 自己
 *   也有一个 `main()`（它的入口线程）。两个 `main()` 在链接期必然冲突。
 *
 *   所以真正的应用逻辑在 `main.c` 里、叫 `gomoku_run()`；**入口按宿主分开**：
 *       · 裸机      -> 本文件（main() 直接调 gomoku_run()）
 *       · RT-Thread -> scripts/rtthread/app/main.c（建线程调 gomoku_run()）
 *
 *   `demo/start.S` 复位后跳到 `main`，裸机构建因此必须链上本文件。
 *   [!] `scripts/rtthread/build.ps1` 的源文件清单里【不能】包含本文件 ——
 *       否则又会多一个 main()。
 * ==========================================================================*/
#include "game.h"

/* 声明在 main.c 里；不放进头文件是因为只有本文件需要它。
 * [!] 五子棋的 .c 都靠 `-I scripts/gomoku` 互相可见。 */
void gomoku_run(void);

int main(void)
{
    gomoku_run();
    return 0;   /* 不会走到：gomoku_run 是 for(;;) */
}
