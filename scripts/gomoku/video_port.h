/* ============================================================================
 * video_port.h —— 固件侧的显示端口（只有固件用，x86 测试不编这个）
 * ----------------------------------------------------------------------------
 * render.c/render.h 是平台无关的；**平台相关的只有这一个文件**：
 *   vid_bulk_write()  —— render.h 声明、这里实现（MMIO 直写显存）
 *   video_set_scroll() / video_wait_vblank()  —— 显示控制，只在固件里有意义
 *
 * 显存映射的唯一真相是 rtl/bus/addr_map.vh，软件侧的影子定义在
 * scripts/demo/addr_map.h（两处必须一致，改一处要同步改另一处）。
 * ==========================================================================*/
#ifndef GOMOKU_VIDEO_PORT_H
#define GOMOKU_VIDEO_PORT_H

#include <stdint.h>

/* 把背景滚动位置设为 (x, y)。棋类是静态的，归零即可 —— 但**必须显式写一次**：
 * 这两个寄存器上电值不确定，不写可能整屏错位。 */
void video_set_scroll(int x, int y);

/* 等进入帧消隐期（vblank）。
 * [!] 改显存最好在 vblank 里做，否则可能撕裂 —— 上半屏是新内容、下半屏是旧的。
 *     棋子一格一格落，最坏撕一格、只影响 1 帧，可以接受；
 *     但**光标移动频繁**，建议顺带等一下。
 *
 * 返回：**0 = 等到了；非 0 = 超时**（视频没在跑，约 50ms ≈ 3 帧后放弃）。
 * [!] 内部带超时保护 —— 原来是无超时忙等，视频一失锁就**永久挂死**（2026-10-07 实踩）。
 *     调用方拿到非 0 可以提示或降级，但**不要因此继续等下去**。 */
int video_wait_vblank(void);

#endif /* GOMOKU_VIDEO_PORT_H */
