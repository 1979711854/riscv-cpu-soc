/* ============================================================================
 * BTB 间接跳转定向测试（B1-BTB）
 * ----------------------------------------------------------------------------
 * 为什么单写这一条：
 *   CoreMark 里的 jalr 几乎 100% 是 `ret`，已被 RAS 以 99.9%+ 命中捕获 ⇒ BTB
 *   在跑分里一次都不触发。于是"CoreMark 逐位不变"既证明不了 BTB 生效，也证明不了
 *   它的纠错路径（§7 目标校验）是对的。本测试专门构造【既非 call 也非 ret】的
 *   间接跳转 `jalr x0,0(tX)`（tX ∉ {x1,x5}）—— 这种跳转只有 BTB 能预测。
 *
 * 两个阶段：
 *   阶段 1（稳定目标）：同一 jalr 站点每次都跳同一地址 ⇒ BTB 训练一次后稳定命中。
 *                     结果自检（循环体必须恰好执行 N 次）。
 *   阶段 2（交替目标）：同一 jalr 站点在 2 个目标间交替 ⇒ 直接映射 BTB 每轮都会
 *                     拿【上一轮】的目标去猜、故除首轮外必猜错 ⇒ 只能靠 §7 纠正。
 *                     若 §7 失效，会沿错误目标执行、落点分布与累加值都会错 ⇒ FAIL。
 *                     （= "把 ex_target_wrong 置 0 就能让本测试挂掉"的承重验证。）
 *
 * 判分用 riscv-tests 的 tohost 机制（sim/tb_riscv.v 已支持）。
 * 探针：vvp `+BTBTRACE` 打印 btb pred / train 次数（纯被动，不改周期数）。
 * 汇编方式见 scripts/run_own_tests.ps1
 * ==========================================================================*/
#include "encoding.h"
#include "riscv_test.h"
#include "test_macros.h"

RVTEST_CODE_BEGIN

    /* ==================== 阶段 1：稳定目标 ==================== */
    li    TESTNUM, 1
    li    s2, 0                 /* 累加器：循环体每执行一次 +1 */
    li    s3, 10                /* 循环体执行次数 */
    la    t3, p1_body           /* 间接跳转目标（t3=x28，非 ra/t0 ⇒ 非 call/ret） */

p1_body:
    addi  s2, s2, 1
    addi  s3, s3, -1
    beqz  s3, p1_done
    jalr  x0, 0(t3)             /* 目标恒为 p1_body ⇒ BTB 训练后稳定命中 */
p1_done:
    li    t0, 10
    bne   s2, t0, fail          /* 循环体须恰好执行 10 次 */

    /* ==================== 阶段 2：交替目标 ==================== */
    /* 同一个 jalr 站点在 p2_a / p2_b 间交替。直接映射 BTB 每个 PC 只存 1 个目标
       ⇒ 每轮只能用【上一轮】的目标去猜，故除首轮外每轮都猜错 ⇒ 全靠 §7 纠正到
       正确路径。两条落地路径用【差异极大】的累加值（+1 / +100）并在 p2_cont 汇合，
       这样一旦某轮走错路径，s4 必然偏离期望值 ⇒ 结果自检 FAIL。 */
    li    TESTNUM, 2
    li    s4, 0                 /* 累加器 */
    li    s6, 6                 /* 间接跳转次数（偶数 ⇒ A、B 各落到 3 次） */
    la    t3, p2_a              /* 首个目标 = A */

p2_loop:
    jalr  x0, 0(t3)             /* 单站点、交替目标 */
p2_a:
    addi  s4, s4, 1             /* 落到 A ⇒ +1 */
    la    t3, p2_b
    j     p2_cont
p2_b:
    addi  s4, s4, 100           /* 落到 B ⇒ +100 */
    la    t3, p2_a
p2_cont:
    addi  s6, s6, -1
    bnez  s6, p2_loop
p2_done:
    /* 落点序列（s6: 6→0）：A B A B A B ⇒ 3×1 + 3×100 = 303 */
    li    t0, 303
    bne   s4, t0, fail

    /* ==================== 全部通过 ==================== */
    RVTEST_PASS

fail:
    RVTEST_FAIL

RVTEST_CODE_END

