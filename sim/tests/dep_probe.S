/* ============================================================================
 * dep_probe.S —— 诊断用探针：不含 AMO，只测「相邻依赖对」在双发射下是否错
 * ----------------------------------------------------------------------------
 * 来历：sim/tests/amo_int.S 在单发射下 UART 收到 2 字节，在双发射下收到 0 字节。
 *   追下去发现 `li t0,0xFFFC`（= lui t0,0x8 ; addi t0,t0,-4）在双发射下
 *   addi 算出的是 0x1FFC —— 说明它读到的 t0 是【上一条 lui t0,0x2 的旧值】，
 *   即 lane A 刚写的 t0 没有前递给同拍配对的 lane B。
 *
 * 本探针把 AMO 拿掉，只留同一段依赖链，用来区分：
 *   - 双发射下 UART 仍是 0f  ⇒ AMO 的 mc_stall 把后续配对搞坏了（AMO 侧问题）
 *   - 双发射下 UART 不是 0f  ⇒ 双发射配对/前递本身对相邻依赖对就是错的（大得多的问题）
 *
 * 判据：UART(0xFFFC) 一个字节 = 0f（t4 重新读回的值 = t1 = 0x0F）。
 * ==========================================================================*/
    .section .text.init
    .globl _start
_start:
    li      sp, 0x7F00

    li      t0, 0x2000
    li      t1, 0x0000000F
    sw      t1, 0(t0)
    lw      t4, 0(t0)             # t4 = 0x0F

    li      t0, 0xFFFC            # lui t0,0x8 ; addi t0,t0,-4  ← 关键依赖对
    sb      t4, 0(t0)

    li      t0, 0xFFF8
    li      t1, 1
    sw      t1, 0(t0)
1:  j       1b
