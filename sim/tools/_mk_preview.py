#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate sim/tools/_main_preview.c from the REAL scripts/gomoku/main.c.

Why: the host preview must use the same layout code as the firmware. We copy
main.c and patch only the two host-hostile spots:

  1) `csrr mimpid`  -> a constant (host has no CSR)
  2) CM_MBOX_BASE   -> a static host array (0xFF00 is not mapped on the host)

Then append preview_render_scene(scene), which sets up a deterministic game
state and calls the real draw_frame().

Run:  python -I sim/tools/_mk_preview.py
"""
import io
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
SRC = os.path.join(REPO, "scripts", "gomoku", "main.c")
DST = os.path.join(HERE, "_main_preview.c")

src = io.open(SRC, encoding="utf-8").read()

# 1) CSR -> constant
src2, n = re.subn(
    r'__asm__\s+volatile\s*\("csrr[^\n]*\n',
    'v = 0x1028u;   /* host preview stub */\n',
    src,
)
if n == 0:
    raise SystemExit("csrr mimpid line not found in main.c -- update _mk_preview.py")

# 2) mailbox -> host array
if "(volatile uint32_t *)CM_MBOX_BASE" not in src2:
    raise SystemExit("CM_MBOX_BASE cast not found in main.c -- update _mk_preview.py")
src2 = src2.replace("(volatile uint32_t *)CM_MBOX_BASE", "g_host_cm_mbox")

anchor = '#include "cm_mailbox.h"'
if anchor not in src2:
    raise SystemExit('cm_mailbox.h include not found in main.c')
i = src2.index(anchor)
i = src2.index("\n", i) + 1
src2 = src2[:i] + "\nstatic uint32_t g_host_cm_mbox[CM_MBOX_N_WORDS];\n" + src2[i:]

HOOK = r'''
/* ==========================================================================
 * Host preview hook (auto-generated by _mk_preview.py -- do not edit)
 * --------------------------------------------------------------------------
 * scene: 0 title / 1 submenu / 2 game / 3 game over
 * Uses the same g_game + draw_frame() as the firmware.
 * ==========================================================================*/
void preview_render_scene(int scene)
{
    render_init();
    render_clear();
    game_init(&g_game, AI_NORMAL, GOMOKU_BLACK, 50);

    /* Fake LAST COREMARK mailbox so the title screen shows the result lines. */
    g_host_cm_mbox[CM_MBOX_I_MAGIC] = CM_MBOX_MAGIC;
    g_host_cm_mbox[CM_MBOX_I_SCORE] = 35250u;      /* 352.50 */
    g_host_cm_mbox[CM_MBOX_I_FLAGS] = CM_MBOX_FLAG_CRC_OK;

    if (scene == 0) {                       /* title */
        g_game.phase     = GAME_TITLE;
        g_game.menu_page = MENU_PAGE_MAIN;
        g_game.menu_cursor = 0;
    } else if (scene == 1) {                /* AI submenu */
        g_game.phase     = GAME_TITLE;
        g_game.menu_page = MENU_PAGE_AI;
        g_game.menu_cursor = 0;
    } else if (scene == 4) {                /* human submenu */
        g_game.phase     = GAME_TITLE;
        g_game.menu_page = MENU_PAGE_HUMAN;
        g_game.menu_cursor = 0;
    } else if (scene == 2) {                /* in-game */
        g_game.mode        = GAME_MODE_HUMAN;
        g_game.human       = GOMOKU_BLACK;
        g_game.level_black = AI_HARD;
        g_game.level_white = AI_HARD;
        game_start(&g_game, 0);
        gomoku_place(&g_game.board, 7, 7);
        gomoku_place(&g_game.board, 7, 8);
        gomoku_place(&g_game.board, 9, 7);
        gomoku_place(&g_game.board, 7, 9);
        gomoku_place(&g_game.board, 11, 6);
        g_game.cursor_r = 7;
        g_game.cursor_c = 10;   /* 空格，能看见光标 */
        g_game.cursor_on = 1;
        g_game.cursor_hidden = 0;
        g_game.ai_nodes = 12874u;
        g_game.ai_depth = 6;
        g_game.ai_ms    = 569u;
    } else {                                /* game over: black wins */
        g_game.mode        = GAME_MODE_HUMAN;
        g_game.human       = GOMOKU_BLACK;
        g_game.level_black = AI_HARD;
        game_start(&g_game, 0);
        gomoku_place(&g_game.board, 7, 3);
        gomoku_place(&g_game.board, 7, 4);
        gomoku_place(&g_game.board, 7, 5);
        gomoku_place(&g_game.board, 7, 6);
        gomoku_place(&g_game.board, 7, 7);
        g_game.phase  = GAME_OVER;
        g_game.winner = GOMOKU_BLACK;
        g_game.ai_nodes = 12874u;
        g_game.ai_depth = 6;
        g_game.ai_ms    = 569u;
    }

    /* 时间轴：标题/子菜单用 0（PRESS ANY KEY 亮）；对局用 750ms，
     * 让 THINKING 落在"亮"相位，截图能看见（固件里 500ms 交替）。 */
    {
        uint32_t now = (scene == 2) ? (750u * hw_ticks_per_ms()) : 0u;
        draw_frame(now);
    }
}
'''

io.open(DST, "w", encoding="utf-8", newline="\n").write(src2 + HOOK)
print("generated", DST)
